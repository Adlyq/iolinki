#!/usr/bin/env python3
"""Generate the SPEC_ENTRY symbol list of tests/test_spec_constants.c.

``tests/spec_constants.csv`` is the data source and ``include/iolinki/protocol.h``
the implementation. The C test has to name every CSV symbol so it can compare
the macro's value with the CSV ``expected`` column, and that list used to be a
third hand-copied source. This script emits the symbols only: the generated
header carries no values, so the CSV and the macros stay independent -- a wrong
value still fails the runtime comparison, while a missing row is a compile or
lookup failure.

The header is included inside the ``k_spec[]`` initializer, so every entry ends
with a comma and the list is a plain initializer list.

Usage:
    tools/gen_spec_constants.py --csv tests/spec_constants.csv --output build/gen/spec_constants_table.h
    tools/gen_spec_constants.py --csv ... --output ... --check   # fail if stale
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

FIELDS = ["clause", "symbol", "expected", "note"]
SYMBOL_RE = re.compile(r"IOLINK_[A-Z0-9_]+")
BANNER = "/* Generated by tools/gen_spec_constants.py -- do not edit. */"


class GenError(Exception):
    """The CSV cannot produce a symbol list; the message says why."""


def read_symbols(csv_path: Path) -> list[str]:
    if not csv_path.is_file():
        raise GenError(f"{csv_path} is missing")
    with csv_path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != FIELDS:
            raise GenError(
                f"{csv_path}: header must be {','.join(FIELDS)} "
                f"(got {','.join(reader.fieldnames or [])})"
            )
        symbols: list[str] = []
        for line_number, row in enumerate(reader, start=2):
            symbol = (row["symbol"] or "").strip()
            if not symbol:
                raise GenError(f"{csv_path}:{line_number}: empty symbol")
            if not SYMBOL_RE.fullmatch(symbol):
                raise GenError(
                    f"{csv_path}:{line_number}: {symbol!r} is not an IOLINK_ macro name"
                )
            if symbol in symbols:
                raise GenError(f"{csv_path}:{line_number}: duplicate symbol {symbol}")
            symbols.append(symbol)
    if not symbols:
        raise GenError(f"{csv_path}: no data rows")
    return symbols


def render(symbols: list[str]) -> str:
    lines = [BANNER, "", "/* Symbol list only: the values come from the macros. */"]
    lines += [f"SPEC_ENTRY({symbol})," for symbol in symbols]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path, help="tests/spec_constants.csv")
    parser.add_argument("--output", required=True, type=Path, help="generated header")
    parser.add_argument(
        "--check", action="store_true", help="verify the header is current; write nothing"
    )
    args = parser.parse_args(argv)

    try:
        content = render(read_symbols(args.csv))
    except GenError as exc:
        print(f"gen-spec-constants: {exc}", file=sys.stderr)
        return 1

    if args.check:
        try:
            current = args.output.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"gen-spec-constants: cannot read {args.output}: {exc}", file=sys.stderr)
            return 1
        if current != content:
            print(
                f"gen-spec-constants: {args.output} is stale; "
                "rerun tools/gen_spec_constants.py",
                file=sys.stderr,
            )
            return 1
        print(f"gen-spec-constants: OK ({args.output} up to date)")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        if args.output.read_text(encoding="utf-8") == content:
            return 0
    except OSError:
        pass
    args.output.write_text(content, encoding="utf-8")
    print(f"gen-spec-constants: wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
